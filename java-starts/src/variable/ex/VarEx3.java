package variable.ex;

// 문제3
// long 타입의 변수를 선언하고, 그 변수를 10000000000(백억)으로 초기화 후 출력
// boolean 타입의 변수 선언하고 그 변수를 true로 초기화 한 후 출력

public class VarEx3 {
    public static void main(String[] args) {

        long longVar = 10000000000L;
        boolean boolVar = true;

        System.out.println(longVar);
        System.out.println(boolVar);

    }
}
