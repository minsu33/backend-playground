package variable;

public class Var7 {
    public static void main(String[] args) {
        // 변수 타입 종류

        int a = 100; // 정수
        double b = 10.5; // 실수
        boolean c = true; // 불리언 true, false만 선언 간으
        char d = 'A'; // 문자 하나
        String e = "Hello Java"; // 문자열을 다루기위한 특별한 타입
        // 변수 타입과 다른 값으로 초기화하면 컴파일 오류.

        System.out.println(a);
        System.out.println(b);
        System.out.println(c);
        System.out.println(d);
        System.out.println(e);

        // 개발자가 직접 넣은 값은 리터럴(literal)이라고 한다.
    }
}
