package variable;

public class Var8 {

    public static void main(String[] args) {
        // 정수
        byte b = 127; // -128 ~ 127
        short s = 32767; // -32,768 ~ 32,767
        int i = 2147483647; // 약 20억

        long l = 9223372036854775807L; // 그냥 매우 큰 범위다~

        // 실수
        float f = 10.0f; // float는 f를 붙여줘야함
        double d = 10.0;

        // 변수 선언에 맞게 메모리 공간을 차지한다.
        // 따라서 메모리 효율을 위해 적합한 변수를 선언



    }
}
